"""Write every agent's exact prompt into docs/agents/prompts/, generated from the
current code and codebook, so the documentation never drifts from what the
models actually receive.

    python scripts/render_prompts.py

Re-run after changing an agent, the codebook, or a persona.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from adrd_review.agents import adjudicator, annotation, curator, debate, eligibility, extraction, screening, triage, verifier  # noqa: E402
from adrd_review.agents.common import render_article, render_screening_rules  # noqa: E402
from adrd_review.codebook import load_codebook  # noqa: E402
from adrd_review.schemas import (  # noqa: E402
    AdjudicationAnswer,
    AnnotationAnswer,
    CuratorAnswer,
    DebateAnswer,
    Decision,
    EvidenceSpan,
    VerifierAnswer,
    Vote,
    Article,
    ExtractionRecord,
    ExtractedField,
    ScreeningAnswer,
    TriageReport,
)

EXAMPLE = Article(
    pmid="00000000",
    title="Accuracy of the Mini-Mental State Examination for dementia in primary care (illustrative example).",
    journal="Example Journal",
    year=2020,
    publication_types=["Journal Article"],
    abstract="BACKGROUND: Example text. METHODS: 500 primary care patients aged 65+ completed the MMSE; "
    "dementia was diagnosed with DSM-IV criteria. RESULTS: Sensitivity 0.85, specificity 0.90.",
)


def block(text: str) -> str:
    return f"```text\n{text}\n```"


def schema_table(model) -> str:
    rows = ["| Field | Type | Instruction sent to the model |", "|---|---|---|"]
    for name, f in model.model_fields.items():
        t = getattr(f.annotation, "__name__", str(f.annotation)).replace("|", "\\|")
        rows.append(f"| `{name}` | `{t}` | {f.description or ''} |")
    return "\n".join(rows)


def main() -> int:
    cb = load_codebook(ROOT / "configs/codebook.yaml")
    out = ROOT / "docs/agents/prompts"
    out.mkdir(parents=True, exist_ok=True)
    extraction_example = ExtractionRecord(instruments=[ExtractedField(value="MMSE", quote="completed the MMSE")])
    header = (
        "<!-- GENERATED by scripts/render_prompts.py. Do not edit by hand. -->\n\n"
        f"Codebook version: `{cb.version}`\n\n"
    )
    pages = {
        "triage.md": (
            "Triage agent: exact prompt",
            triage.SYSTEM.format(rules=render_screening_rules(cb)),
            render_article(EXAMPLE),
            TriageReport,
        ),
        "screening.md": (
            "Screening reviewer: exact prompt (no persona)",
            screening.system_prompt(cb),
            render_article(EXAMPLE),
            ScreeningAnswer,
        ),
        "extraction.md": (
            "Extraction agent: exact prompt",
            extraction.SYSTEM.format(evidence_rules=__import__("adrd_review.agents.common", fromlist=["x"]).EVIDENCE_RULES),
            render_article(EXAMPLE),
            ExtractionRecord,
        ),
        "annotation.md": (
            "Annotation reviewer: exact prompt (no persona)",
            annotation.system_prompt(cb),
            render_article(EXAMPLE) + annotation.render_extraction(extraction_example),
            AnnotationAnswer,
        ),
    }
    votes = [
        Vote(reviewer_id="A", model="example", field="screening", labels=["include"], rule_ids=["I1", "I2"],
             evidence=[EvidenceSpan(quote="500 primary care patients aged 65+ completed the MMSE")],
             rationale="MMSE evaluated against DSM-IV diagnosis in primary care.", confidence=0.8),
        Vote(reviewer_id="B", model="example", field="screening", labels=["exclude"], rule_ids=["I3"],
             evidence=[EvidenceSpan(quote="Sensitivity 0.85, specificity 0.90.")],
             rationale="Design not reported; cannot confirm a cross-sectional sample.", confidence=0.6),
        Vote(reviewer_id="C", model="example", field="screening", labels=["include"], rule_ids=["I1"],
             evidence=[], rationale="Benefit of the doubt at abstract stage.", confidence=0.7),
    ]
    decision = Decision(field="screening", labels=["include"], method="adjudicator", confidence=0.8)
    disagreement = [{
        "pmid": "00000000", "title": EXAMPLE.title, "abstract": EXAMPLE.abstract, "field": "screening",
        "gold": "exclude", "agent": "include", "rules": ["I4"],
        "reasons": ["Primary care setting assumed to satisfy I4 for MMSE."],
    }]
    paper = EXAMPLE.model_copy(update={"fulltext": (
        "[METHODS] We recruited 500 consecutive primary care patients aged 65 and over. All completed the MMSE. "
        "Dementia was diagnosed with DSM-IV criteria by a clinician blind to the MMSE score.\n\n"
        "[RESULTS] At a cut-off of 24 the MMSE had sensitivity 0.85 and specificity 0.90."
    )})
    pages["eligibility.md"] = (
        "Full-text eligibility reviewer (stage 2): exact prompt (no persona)",
        eligibility.system_prompt(cb),
        eligibility.user_prompt(paper),
        ScreeningAnswer,
    )
    pages |= {
        "adjudicator.md": (
            "Adjudicator: exact prompt (screening decision)",
            adjudicator.system_prompt(cb, "screening"),
            adjudicator.user_prompt(EXAMPLE, votes),
            AdjudicationAnswer,
        ),
        "verifier.md": (
            "Verifier: exact prompt (model check)",
            verifier.SYSTEM.format(rules=render_screening_rules(cb)),
            verifier.user_prompt(EXAMPLE, [decision], votes),
            VerifierAnswer,
        ),
        "debate.md": (
            "Debate (variant D): exact prompt for reviewer B, round 1 (no persona)",
            debate.system_prompt(cb, "screening"),
            debate.user_prompt(EXAMPLE, votes[1], votes),
            DebateAnswer,
        ),
        "curator.md": (
            "Codebook Curator: exact prompt",
            curator.SYSTEM.format(
                version=cb.version,
                rules=render_screening_rules(cb),
                dimensions=__import__("adrd_review.agents.common", fromlist=["x"]).render_dimensions(cb),
            ),
            f"DISAGREEMENTS ({len(disagreement)})\n\n" + curator.render_disagreements(disagreement),
            CuratorAnswer,
        ),
    }
    for fname, (title, system, user, schema) in pages.items():
        text = (
            f"# {title}\n\n{header}"
            "## System message\n\n" + block(system) + "\n\n"
            "## User message (illustrative article)\n\n" + block(user) + "\n\n"
            f"## Answer form the model must fill (`{schema.__name__}`)\n\n" + schema_table(schema) + "\n"
        )
        (out / fname).write_text(text)
        print(f"wrote docs/agents/prompts/{fname}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
